"""Animated maps drawn from real geography (Natural Earth, public domain).

In episode.yaml, a scene can carry maps timed to the narration, like cards:

    maps:
      - match: "Genoese ships then carried"     # sentence that starts the map
        sentences: 2                             # how many sentences it stays on screen
        style: route                             # route = a line drawn point to point
                                                 # spread = points light up one after another
        title: "The road of the Black Death"
        region: [-12, 30, 75, 62]                # lon_min, lat_min, lon_max, lat_max (optional, else fitted)
        points:
          - [35.4, 45.0, "Caffa 1346"]
          - [28.9, 41.0, "Constantinople 1347"]
          - [15.5, 38.2, "Sicily, Oct 1347"]

Vintage look: parchment, ink coastlines, graticule. Nothing here is generated by AI.
"""
from __future__ import annotations

import json
import math
from functools import lru_cache
from pathlib import Path

import cv2
import numpy as np
from PIL import Image, ImageDraw


ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data"
INK = (52, 40, 28)
RED = (150, 32, 24)
LAND = (214, 197, 160)
SEA = (182, 190, 178)


@lru_cache(maxsize=2)
def _polys(name: str):
    d = json.loads((DATA / name).read_text())
    out = []
    for f in d["features"]:
        g = f["geometry"]
        rings = [g["coordinates"]] if g["type"] == "Polygon" else g["coordinates"]
        for poly in rings:
            out.append([np.array(r, dtype=np.float64) for r in poly])
    return out


class Projection:
    """Equirectangular, scaled by cos(mid-latitude) so local maps are not stretched."""

    def __init__(self, region, W, H, pad=0.08):
        lon0, lat0, lon1, lat1 = region
        k = math.cos(math.radians((lat0 + lat1) / 2))
        w, h = (lon1 - lon0) * k, (lat1 - lat0)
        # grow the region to the frame's aspect
        if w / h < W / H:
            extra = (h * W / H - w) / k
            lon0, lon1 = lon0 - extra / 2, lon1 + extra / 2
        else:
            extra = w * H / W - h
            lat0, lat1 = lat0 - extra / 2, lat1 + extra / 2
        self.lon0, self.lat1, self.k = lon0, lat1, k
        self.s = min((W * (1 - 2 * pad)) / ((lon1 - lon0) * k), (H * (1 - 2 * pad)) / (lat1 - lat0))
        self.ox = (W - (lon1 - lon0) * k * self.s) / 2
        self.oy = (H - (lat1 - lat0) * self.s) / 2
        self.region = (lon0, lat0, lon1, lat1)

    def __call__(self, lon, lat):
        x = self.ox + (np.asarray(lon) - self.lon0) * self.k * self.s
        y = self.oy + (self.lat1 - np.asarray(lat)) * self.s
        return x, y


def fit_region(points, margin=0.35):
    lons = [p[0] for p in points]
    lats = [p[1] for p in points]
    dl = max(max(lons) - min(lons), 6)
    dt = max(max(lats) - min(lats), 4)
    return [min(lons) - dl * margin, max(min(lats) - dt * margin, -85),
            max(lons) + dl * margin, min(max(lats) + dt * margin, 85)]


def base_map(region, W, H, title: str | None = None) -> tuple[np.ndarray, Projection]:
    """Parchment map with land, lakes, coastline ink and graticule. Returns RGB array + projection."""
    from .render import draw_tracked, font
    P = Projection(region, W, H)
    S = 2  # supersample for clean lines
    img = Image.new("RGB", (W * S, H * S), SEA)
    d = ImageDraw.Draw(img)
    lon0, lat0, lon1, lat1 = P.region

    def pts(ring):
        x, y = P(ring[:, 0], ring[:, 1])
        return list(zip((x * S).tolist(), (y * S).tolist()))

    for poly in _polys("ne_50m_land.geojson"):
        r = poly[0]
        if r[:, 0].max() < lon0 - 5 or r[:, 0].min() > lon1 + 5 or r[:, 1].max() < lat0 - 5 or r[:, 1].min() > lat1 + 5:
            continue
        d.polygon(pts(r), fill=LAND, outline=INK, width=max(2, int(1.6 * S * W / 1920)))
        for hole in poly[1:]:
            d.polygon(pts(hole), fill=SEA)
    for poly in _polys("ne_50m_lakes.geojson"):
        r = poly[0]
        if r[:, 0].max() < lon0 or r[:, 0].min() > lon1 or r[:, 1].max() < lat0 or r[:, 1].min() > lat1:
            continue
        d.polygon(pts(r), fill=SEA, outline=INK)
    # graticule
    step = 5 if (lon1 - lon0) < 60 else 10 if (lon1 - lon0) < 150 else 30
    gcol = (120, 108, 88)
    for lo in range(int(math.floor(lon0 / step) * step), int(lon1) + step, step):
        x, _ = P(lo, 0)
        d.line([(x * S, 0), (x * S, H * S)], fill=gcol, width=1)
    for la in range(int(math.floor(lat0 / step) * step), int(lat1) + step, step):
        _, y = P(0, la)
        d.line([(0, y * S), (W * S, y * S)], fill=gcol, width=1)
    img = img.resize((W, H), Image.LANCZOS)
    a = np.array(img).astype(np.float32)
    # paper texture + vignette
    rng = np.random.default_rng(7)
    n = cv2.resize(rng.normal(0, 1, (H // 12, W // 12)).astype(np.float32), (W, H), interpolation=cv2.INTER_CUBIC)
    a += (n * 7 + rng.normal(0, 3, (H, W)).astype(np.float32))[..., None]
    yy, xx = np.ogrid[-1:1:H * 1j, -1:1:W * 1j]
    a *= (1 - 0.32 * np.clip(np.sqrt(xx * xx * 0.8 + yy * yy) - 0.5, 0, 1))[..., None]
    img = Image.fromarray(a.clip(0, 255).astype(np.uint8))
    if title:
        d = ImageDraw.Draw(img)
        s = W / 1920
        f = font("Oswald.ttf", int(46 * s), 600)
        tw = draw_tracked(d, (W / 2, H * 0.045), title.upper(), f, INK, tracking=int(6 * s))
        d.line([(W / 2 - tw / 2, H * 0.045 + 62 * s), (W / 2 + tw / 2, H * 0.045 + 62 * s)], fill=INK, width=max(1, int(2 * s)))
    return np.array(img), P


class MapShot:
    """Pre-rendered map + per-frame animation of the route or the spread."""

    def __init__(self, spec: dict, W: int, H: int):
        pts = spec["points"]
        region = spec.get("region") or fit_region(pts)
        base, P = base_map(region, W, H, spec.get("title"))
        self.base = cv2.cvtColor(base, cv2.COLOR_RGB2BGR)
        self.W, self.H = W, H
        self.style = spec.get("style", "route")
        self.xy = [tuple(float(v) for v in P(p[0], p[1])) for p in pts]
        self.labels = [p[2] if len(p) > 2 else "" for p in pts]
        s = W / 1920
        self.s = s
        self.lab_imgs = [self._label(t) for t in self.labels]
        self.lab_pos = self._place_labels()
        # cumulative route length, to draw at constant speed
        seg = [math.dist(self.xy[i], self.xy[i + 1]) for i in range(len(self.xy) - 1)]
        self.cum = np.concatenate([[0], np.cumsum(seg)]) if seg else np.array([0.0])

    def _label(self, text):
        from .render import font
        if not text:
            return None
        f = font("EBGaramond-Italic.ttf", int(40 * self.s), 600)
        tmp = ImageDraw.Draw(Image.new("RGBA", (1, 1)))
        w = int(tmp.textlength(text, font=f)) + int(24 * self.s)
        h = int(58 * self.s)
        im = Image.new("RGBA", (w, h), (0, 0, 0, 0))
        d = ImageDraw.Draw(im)
        d.rounded_rectangle([0, 0, w - 1, h - 1], radius=int(6 * self.s), fill=(238, 228, 204, 225), outline=INK + (255,))
        d.text((int(12 * self.s), int(6 * self.s)), text, font=f, fill=INK + (255,))
        return cv2.cvtColor(np.array(im), cv2.COLOR_RGBA2BGRA)

    def _place_labels(self):
        """Put each label in one of 8 positions around its point, avoiding earlier labels and points."""
        placed, out = [], []
        g = 16 * self.s
        for (x, y), lab in zip(self.xy, self.lab_imgs):
            if lab is None:
                out.append(None)
                continue
            h, w = lab.shape[:2]
            cands = [(x + g, y - h - g), (x + g, y + g), (x - w - g, y - h - g), (x - w - g, y + g),
                     (x - w / 2, y - h - 2 * g), (x - w / 2, y + 2 * g), (x + g, y - h / 2), (x - w - g, y - h / 2)]
            best, best_cost = None, None
            for cx, cy in cands:
                cx = float(np.clip(cx, 4, self.W - w - 4))
                cy = float(np.clip(cy, 4, self.H - h - 4))
                box = (cx, cy, cx + w, cy + h)
                cost = sum(max(0, min(box[2], b[2]) - max(box[0], b[0])) * max(0, min(box[3], b[3]) - max(box[1], b[1]))
                           for b in placed)
                cost += sum(1e5 for (px, py) in self.xy if box[0] - 6 < px < box[2] + 6 and box[1] - 6 < py < box[3] + 6)
                if best_cost is None or cost < best_cost:
                    best, best_cost = box, cost
            placed.append(best)
            out.append((int(best[0]), int(best[1])))
        return out

    def _paste(self, frame, lab, pos, alpha):
        if lab is None or alpha <= 0 or pos is None:
            return
        h, w = lab.shape[:2]
        x0, y0 = pos
        roi = frame[y0:y0 + h, x0:x0 + w]
        a = lab[..., 3:4].astype(np.float32) / 255 * alpha
        roi[:] = (roi * (1 - a) + lab[..., :3] * a).astype(np.uint8)

    def frame(self, p: float) -> np.ndarray:
        """p = 0..1 progress through the shot."""
        f = self.base.copy()
        n = len(self.xy)
        draw_p = min(1.0, p / 0.8)          # finish drawing at 80% of the shot, then hold
        th = max(2, int(5 * self.s))
        red = RED[::-1]
        ink = INK[::-1]
        if self.style == "route" and n > 1:
            L = draw_p * self.cum[-1]
            path = [self.xy[0]]
            for i in range(1, n):
                if self.cum[i] <= L:
                    path.append(self.xy[i])
                else:
                    t = (L - self.cum[i - 1]) / max(self.cum[i] - self.cum[i - 1], 1e-6)
                    a, b = self.xy[i - 1], self.xy[i]
                    path.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
                    break
            pts = np.array(path, np.int32).reshape(-1, 1, 2)
            cv2.polylines(f, [pts], False, red, th + 2, cv2.LINE_AA)
            hx, hy = path[-1]
            cv2.circle(f, (int(hx), int(hy)), int(9 * self.s), red, -1, cv2.LINE_AA)
            reached = [i for i in range(n) if self.cum[i] <= L + 1e-6]
        else:   # spread: points appear one by one with an expanding ring
            reached = []
            for i in range(n):
                t0 = i / max(n, 1)
                if draw_p >= t0:
                    reached.append(i)
                    age = (draw_p - t0) * n
                    x, y = self.xy[i]
                    rr = int((10 + 60 * min(age, 1.0)) * self.s)
                    al = max(0.0, 1 - age)
                    if al > 0:
                        ov = f.copy()
                        cv2.circle(ov, (int(x), int(y)), rr, red, max(2, int(4 * self.s)), cv2.LINE_AA)
                        f = cv2.addWeighted(ov, al, f, 1 - al, 0)
        for i in reached:
            x, y = self.xy[i]
            cv2.circle(f, (int(x), int(y)), int(11 * self.s), ink, -1, cv2.LINE_AA)
            cv2.circle(f, (int(x), int(y)), int(6 * self.s), (220, 230, 238), -1, cv2.LINE_AA)
            self._paste(f, self.lab_imgs[i], self.lab_pos[i], 1.0)
        return f
